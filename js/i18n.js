// Idioma a usar: el guardado, o el del navegador la primera vez
BOTD.resolveLang = function (saved) {
  const L = BOTD.I18N.LANGS;
  if (L.includes(saved)) return saved;
  const nav = (navigator.languages && navigator.languages[0]) || navigator.language || 'es';
  const code = String(nav).slice(0, 2).toLowerCase();
  return L.includes(code) ? code : 'es';
};

BOTD.setLang = function (lang) {
  if (BOTD.I18N.LANGS.includes(lang)) BOTD.I18N.lang = lang;
};

BOTD.t = function (key, vars) {
  const I = BOTD.I18N;
  let s = (I.strings[I.lang] || {})[key];
  if (s == null) s = I.strings.es[key];
  if (s == null) return key;
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  return s;
};

BOTD.applyI18n = function (root) {
  const r = root || document;
  r.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = BOTD.t(el.dataset.i18n); });
  r.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = BOTD.t(el.dataset.i18nPlaceholder); });
  r.querySelectorAll('[data-i18n-aria]').forEach(el => {
    const txt = BOTD.t(el.dataset.i18nAria);
    el.setAttribute('aria-label', txt);
    el.title = txt;
  });
  document.documentElement.lang = BOTD.I18N.lang;
};
